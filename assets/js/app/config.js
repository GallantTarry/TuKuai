/**
 * ============================================================================
 * 文件路径：assets/assets/js/app/config.js
 * 文件作用：全站的【总配置文件】与【全局百宝箱初始化】（必须是第一个加载的业务脚本）
 * ============================================================================
 *
 * 【通俗理解：这个文件是干嘛的？】
 * 1. 建立一个全站共用的“大百宝箱” —— `window.TuKuai`（在代码里简写为 `TK`）：
 *    因为我们的网站没有使用 Webpack / Vite 等复杂的打包工具，而是直接用 `<script>` 标签引入各个 JS 文件。
 *    为了让不同 JS 文件之间能够互相拿东西，我们在浏览器的全局对象 `window` 上挂了一个名叫 `TuKuai` 的对象。
 *    里面分了 5 个抽屉：
 *      - `TK.config`      ：放全站的固定配置（网址、接口地址、缓存名字等，就是本文件的内容）
 *      - `TK.utils`       ：放通用的小工具函数（在 utils/helpers.js 里往里装）
 *      - `TK.data`        ：放全站的数据，比如游戏列表、歌单、工具网址（在 data/*.js 里往里装）
 *      - `TK.components`  ：放可复用的网页积木组件，比如卡片、密函弹窗（在 components/*.js 里往里装）
 *      - `TK.composables` ：放各个板块的功能逻辑，比如音乐播放、画板、时钟（在 composables/*.js 里往里装）
 *
 * 2. 把全站所有可能会改动的“网址、接口、开关参数”集中放在这里：
 *    以后如果你换了后端服务器域名、换了博客跳转链接、或者想把邮件附件上限从 5MB 改成 10MB，
 *    不需要去几千行代码里大海捞针，直接改下面对应的那一行字就行了！
 */
(function (TK) {
    'use strict'; // 开启严格模式：让浏览器帮我们检查低级语法错误（比如用了未声明的变量）

    // ========================================================================
    // 第一步：在 `window.TuKuai` 大百宝箱里先把 4 个空抽屉准备好
    // 后面加载的其他 JS 文件会直接往这 4 个抽屉里塞东西
    // ========================================================================
    TK.utils = {};       // 抽屉 1：存放通用工具函数
    TK.data = {};        // 抽屉 2：存放歌单、游戏、网址等纯数据
    TK.components = {};  // 抽屉 3：存放 Vue 组件（卡片、密函弹窗）
    TK.composables = {}; // 抽屉 4：存放各个功能的逻辑模块

    // ========================================================================
    // 第二步：定义全站配置 `TK.config`
    // 说明：`Object.freeze(...)` 的意思是“把配置冻住”，防止其他代码不小心改乱这里的配置值
    // ========================================================================
    TK.config = Object.freeze({

        /**
         * 【后端服务器接口地址】
         * 这三个地址都是你部署在 Cloudflare 上的后端服务（Worker）
         */
        api: Object.freeze({
            /**
             * 「密函发送」邮件接口地址（在 components/mail-modal.js 中使用）
             * 当访客点击头像打开密函弹窗、填好内容点“发送”时，网页会往这个地址发 POST 请求
             */
            mail: 'https://api.xn--udsye.art',

            /**
             * 「fans 粉丝数 / 访客统计」接口地址（在 composables/use-uv-counter.js 中使用）
             * 网页打开时以及每隔 30 秒，会往这个地址发 GET 请求，获取最新的全站独立访客总数
             */
            uv: 'https://tukuai-kv.xn--udsye.art/api/uv',

            /**
             * 「土块画板」全服实时同步的 WebSocket 地址（在 composables/use-board.js 中使用）
             * 注意开头是 `wss://`（加密的 WebSocket 长连接），用于让所有在线访客实时看到彼此画的线条
             */
            boardWs: 'wss://board.xn--udsye.art/ws'
        }),

        /**
         * 【页面跳转与内嵌链接】
         */
        links: Object.freeze({
            /**
             * 点击右上角（手机端在头部右侧）的 GitHub 图标 + 实时时钟时，在弹窗里打开的日常博客页面路径
             */
            blog: './daily.html',

            /**
             * 在「我的简介」页点击底部名言 "Not all those who wander are lost." 后，
             * 播放完 4.5 秒黑屏坍缩动画后，整个浏览器页面跳转过去的目标网址
             */
            wanderJump: 'https://gallanttarry.github.io/GallantTarry/',

            /**
             * 在「我的简介」页点击 5 个彩色性格胶囊按钮（Hodophile 等）后，
             * 播放完 2.5 秒五色花瓣聚变绽放动画后，整个浏览器页面跳转过去的目标网址
             */
            phileJump: 'https://xn--2esp7m.xn--udsye.art/intro.html'
        }),

        /**
         * 【浏览器本地存储（localStorage）的键名（名字）】
         * 什么是 localStorage？它是浏览器自带的一个“小记事本”，存在用户自己的电脑/手机里，关掉网页也不会丢。
         * 我们用下面这 3 个名字在用户的浏览器里记 3 件事：
         */
        storageKeys: Object.freeze({
            /**
             * 记录“这台设备的唯一身份证号（UUID）”
             * 用来配合上面的 uv 接口识别是不是同一个老访客，避免同一个人刷新页面把粉丝数刷高
             */
            deviceUuid: 'tukuai_device_uuid',

            /**
             * 记录“这个用户是不是已经看过开机 PowerShell 动画了”
             * 第一次进网站没这个记录 -> 播开机动画 -> 播完存一个 `'true'` 进去 -> 下次再来直接进主页，不耽误时间
             */
            booted: 'os_booted',

            /**
             * 记录“这个用户有没有点过左下角的 Cookie 授权弹窗”
             * 点了同意存 `'accepted'`，点了拒绝存 `'declined'`；只要存过了，下次刷新就不再弹窗打扰
             */
            cookieConsent: 'tukuai_cookie_consent'
        }),

        /**
         * 【开机动画显示的命令行文字】
         * 首次开机时，PowerShell 窗口里 `PS C:\Users\土块>` 后面从乱码逐字解码出来的那串命令
         */
        bootCommand: 'irm xn--udsye.art|iex',

        /**
         * 【手机锁屏 / 苹果灵动岛 / 系统媒体控制中心显示的信息】
         * 当用户在「电子音乐」里放歌时，手机锁屏界面和苹果灵动岛上会显示歌名、歌手名和封面图
         */
        mediaSession: Object.freeze({
            /** 锁屏界面上显示的“歌手/作者名”，你可以随时改成你想要的名字 */
            artist: 'TuKuai OS',

            /**
             * 锁屏和灵动岛上显示的专辑封面图
             * 重要提示：苹果灵动岛如果抓到透明背景的图标会显示成奇怪的白块，所以这里专门指定一张实心黑底图片
             */
            artwork: Object.freeze({src: './assets/images/ui/music-cover.png', sizes: '180x180', type: 'image/png'})
        }),

        /**
         * 【密函弹窗中，允许上传的单个附件最大体积（单位：字节 Byte）】
         * 计算方式：1MB = 1024KB = 1024 * 1024 字节。
         * 这里的 `5 * 1024 * 1024` 就代表 5MB。如果想改成 10MB，把开头的 `5` 改成 `10` 即可。
         */
        mailMaxFileSize: 5 * 1024 * 1024
    });

})(window.TuKuai = window.TuKuai || {});
// ↑ 上面这一行 `(window.TuKuai = window.TuKuai || {})` 的意思是：
// 如果全局还没有 `window.TuKuai`，就新建一个空对象 `{}` 赋给它，并作为参数 `TK` 传进上面的函数里。
