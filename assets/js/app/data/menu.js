/**
 * ============================================================================
 * 文件路径：assets/js/app/data/menu.js
 * 文件作用：配置页面左侧（手机端为顶部）的【导航栏菜单项】与【各板块专属主题色】
 * ============================================================================
 *
 * 【通俗理解：这个文件是干嘛的？】
 * 页面左边有 6 个导航按钮（我的简介、在线使用、文件下载、电子音乐、复古游戏、创意空间）。
 * 你会发现：每当你点一个不同的导航按钮，全站的颜色（包括头像外框、粉丝数颜色、时钟颜色、音乐播放键、弹窗边框）
 * 都会跟着变成那个板块的代表色！
 *
 * 这 6 个按钮的名字、图标、以及它们各自的代表色，全部是由下面这个 `TK.data.menuItems` 数组控制的。
 *
 * 【每一项里的 4 个属性分别是什么意思？】
 *   - `id`    ：板块的“内部英文代号”。
 *               必须和 `index.html` 里的 `v-if="currentTab === 'xxx'"` 完全对应，千万不要随便改名！
 *   - `title` ：导航按钮上显示的中文名称（比如 `'我的简介'`），你可以随时修改文字。
 *   - `icon`  ：导航按钮左边显示的 Emoji 表情图标（比如 `'🤪'`），可以直接替换成别的表情。
 *   - `color` ：切到这个板块时，全站的【霓虹主题色】（十六进制颜色代码，比如 `'#38bdf8'` 是天蓝色）。
 *
 * 【想新增一个板块怎么办？】
 *   1. 在下面的 `TK.data.menuItems` 数组末尾照着格式加一行：`{id: 'newtab', title: '新板块', icon: '✨', color: '#ec4899'}`
 *   2. 去 `index.html` 的右侧 `<main>` 面板里，加一个 `<tab-section title="> 新板块" v-if="currentTab === 'newtab'">...</tab-section>`
 */
(function (TK) {
    'use strict';

    /**
     * 左侧导航栏的 6 个板块配置列表
     * 数组里的先后顺序，就是网页上导航按钮从上到下（手机端从左到右）的排列顺序
     */
    TK.data.menuItems = [
        {id: 'about',    title: '我的简介', icon: '🤪', color: '#38bdf8'}, // 天蓝色（默认打开的第一个板块）
        {id: 'online',   title: '在线使用', icon: '🌐', color: '#4ade80'}, // 赛博绿
        {id: 'download', title: '文件下载', icon: '📦', color: '#facc15'}, // 明黄色
        {id: 'music',    title: '电子音乐', icon: '🎵', color: '#a855f7'}, // 霓虹紫
        {id: 'games',    title: '复古游戏', icon: '🎮', color: '#ef4444'}, // 街机红
        {id: 'model',    title: '创意空间', icon: '🧊', color: '#6366f1'}  // 靛蓝色
    ];

    /**
     * 默认兜底主题色：
     * 万一程序没找到当前板块对应的颜色时，就用这个天蓝色 `#38bdf8` 保底，防止页面颜色丢失
     */
    TK.data.defaultThemeColor = '#38bdf8';

})(window.TuKuai);
